# CONTRIBUTING.md rule 2 for the apply engine: a generated secret is returned only as a
# SecureString on the apply result. It must not appear in the plan, the plan file, the
# audit log, verbose/warning/information output, or error text. The literal below is a
# seeded fake used only to search for leaks.

BeforeAll {
    . (Join-Path $PSScriptRoot '..' 'helpers' 'TestHelpers.ps1')
    . (Join-Path $PSScriptRoot '..' 'helpers' 'PlanFixtures.ps1')
    Import-TenureForTest
    # Plans here name made-up users and run without FakeGraph: the protection preflight compares names only.
    Disable-TestIdentityLookup

    $script:SavedConfirmPreference = $global:ConfirmPreference
    $global:ConfirmPreference = 'None'
    $script:SavedAuditEnv = $env:TENURE_AUDIT_PATH
    $script:Literal = 'ZQ9-seeded-secret-7x'
    $script:FakeNames = @('Fake.Secret', 'Fake.SecretGet', 'Fake.Leaky', 'Fake.Loud', 'Fake.Plain', 'Fake.State', 'Fake.PlainGet')

    function New-SecretWorld {
        Set-TenureTestSession
        $script:state = @{ 'u1' = @{ accountEnabled = $true; department = 'Sales' }; 'u2' = @{ accountEnabled = $true; department = 'Sales' } }
        $script:audit = Join-Path $TestDrive ("audit-{0}.jsonl" -f [guid]::NewGuid().ToString('N'))
        $script:out = Join-Path $TestDrive ("plan-{0}.json" -f [guid]::NewGuid().ToString('N'))
        $env:TENURE_AUDIT_PATH = Join-Path $TestDrive 'env-sentinel.jsonl'
    }

    function New-SecretStep([string]$Id, [string]$Provider, [string]$UserId = 'u1') {
        New-TestStep -Id $Id -Provider $Provider -Target @{ Kind = 'user'; Id = $UserId; Name = "$UserId@example.com" } -Before (Get-TestSnapshot -State $script:state -Id $UserId) -After @{ accountEnabled = $false }
    }

    # Runs the plan with every stream merged into the output, and splits the result from the text.
    function Invoke-Captured([object]$Plan) {
        $all = @(Invoke-TenurePlan -Plan $Plan -AuditPath $script:audit -OutFile $script:out -Confirm:$false -Verbose -Debug -InformationAction Continue 3>&1 4>&1 5>&1 6>&1)
        $result = @($all | Where-Object { $_ -is [psobject] -and $_.PSObject.TypeNames -contains 'Tenure.ApplyResult' })
        $text = @($all | Where-Object { -not ($_.PSObject.TypeNames -contains 'Tenure.ApplyResult') } | ForEach-Object {
                if ($_ -is [System.Management.Automation.InformationRecord]) { [string]$_.MessageData }
                elseif ($_ -is [System.Management.Automation.InformationalRecord]) { $_.Message }
                else { [string]$_ }
            }) -join "`n"
        @{ Result = $result[0]; Text = $text }
    }

    function Assert-NoLiteral([string]$Text, [string]$Where) {
        $Text.Contains($script:Literal) | Should -BeFalse -Because "the seeded secret must not appear in $Where"
    }
}

AfterAll {
    $global:ConfirmPreference = $script:SavedConfirmPreference
    $env:TENURE_AUDIT_PATH = $script:SavedAuditEnv
    Unregister-TestProvider -Name $script:FakeNames
    Clear-TenureTestSession
}

Describe 'A secret generated by Set' {
    BeforeEach {
        New-SecretWorld
        $state = $script:state
        $literal = $script:Literal
        $set = {
            param($Target, $Desired, $Current, $Context)
            $secure = [securestring]::new()
            foreach ($character in $literal.ToCharArray()) { $secure.AppendChar($character) }
            $Context.Secrets[$Context.StepId] = $secure
            foreach ($key in $Desired.Keys) { $state[$Target.Id][$key] = $Desired[$key] }
            [pscustomobject]$state[$Target.Id].Clone()
        }.GetNewClosure()
        Register-TestProvider (New-FakeProviderDefinition -Name 'Fake.Secret' -State $script:state -Overrides @{ Set = $set; Risk = 'High' })
    }

    It 'is returned only as a SecureString on the result' {
        $plan = New-TestPlan -Steps @(New-SecretStep 'S01' 'Fake.Secret')
        $captured = Invoke-Captured $plan
        $result = $captured.Result

        $plan.Steps[0].Status | Should -Be 'Applied'
        $result.Secrets['S01'] | Should -BeOfType [securestring]
        ConvertFrom-TestSecureString $result.Secrets['S01'] | Should -Be $script:Literal

        $captured.Text | Should -Match 'S01' -Because 'the verbose stream was captured'
        Assert-NoLiteral $captured.Text 'verbose, warning or information output'
        Assert-NoLiteral ([System.IO.File]::ReadAllText($script:audit)) 'the audit file'
        Assert-NoLiteral ([System.IO.File]::ReadAllText($script:out)) 'the -OutFile plan'
        Assert-NoLiteral (ConvertTo-Json -InputObject ($result | Select-Object -Property * -ExcludeProperty Secrets) -Depth 20) 'the result without Secrets'
        Assert-NoLiteral (ConvertTo-Json -InputObject $result -Depth 20) 'the result serialized with its SecureString'
        $canonical = Invoke-InTenure { param($p) Get-TenureCanonicalJson -InputObject $p } @($plan)
        Assert-NoLiteral $canonical 'the canonical plan'
        Assert-NoLiteral (($Error | ForEach-Object { "$_" }) -join "`n") 'the $Error list'
    }

    It 'stays out of every output when a later step fails with an error that echoes it' {
        $literal = $script:Literal
        $loud = { param($Target, $Desired, $Current, $Context) throw "Graph rejected the request: password '$literal' is not allowed here" }.GetNewClosure()
        Register-TestProvider (New-FakeProviderDefinition -Name 'Fake.Loud' -State $script:state -Overrides @{ Set = $loud })
        $plan = New-TestPlan -Steps @((New-SecretStep 'S01' 'Fake.Secret'), (New-SecretStep 'S02' 'Fake.Loud' -UserId 'u2'))
        $captured = Invoke-Captured $plan

        Get-TestStatus $plan | Should -Be 'Applied,Failed'
        $plan.Steps[1].Result.Error | Should -Match '\[redacted\]'
        Assert-NoLiteral $plan.Steps[1].Result.Error 'Result.Error'
        Assert-NoLiteral $captured.Text 'verbose output'
        Assert-NoLiteral ([System.IO.File]::ReadAllText($script:audit)) 'the audit file'
        Assert-NoLiteral ([System.IO.File]::ReadAllText($script:out)) 'the -OutFile plan'
        $globalErrors = @(Get-Variable -Name Error -Scope Global -ValueOnly | ForEach-Object { "$_"; if ($_ -is [System.Management.Automation.ErrorRecord]) { $_.Exception.ToString() } }) -join "`n"
        Assert-NoLiteral $globalErrors 'the global $Error list'
    }

    It 'is withheld when a buggy provider returns it in the state object' {
        $state = $script:state
        $literal = $script:Literal
        $leaky = {
            param($Target, $Desired, $Current, $Context)
            $secure = [securestring]::new()
            foreach ($character in $literal.ToCharArray()) { $secure.AppendChar($character) }
            $Context.Secrets[$Context.StepId] = $secure
            $state[$Target.Id]['accountEnabled'] = $false
            [pscustomobject]@{ accountEnabled = $false; department = 'Sales'; passwordProfile = @{ password = $literal } }
        }.GetNewClosure()
        $leakyGet = {
            param($Target, $Context)
            $current = [pscustomobject]$state[$Target.Id].Clone()
            if ($current.accountEnabled -eq $false) { $current | Add-Member -NotePropertyName 'lastPassword' -NotePropertyValue $literal }
            $current
        }.GetNewClosure()
        Register-TestProvider (New-FakeProviderDefinition -Name 'Fake.Leaky' -State $script:state -Overrides @{ Set = $leaky; Get = $leakyGet })
        $plan = New-TestPlan -Steps @(New-SecretStep 'S01' 'Fake.Leaky')
        $captured = Invoke-Captured $plan

        $plan.Steps[0].Status | Should -Be 'Failed'
        $plan.Steps[0].Result.Error | Should -Match 'SecretRejected'
        $plan.Steps[0].Result.Observed | Should -BeNullOrEmpty
        ConvertFrom-TestSecureString $captured.Result.Secrets['S01'] | Should -Be $script:Literal
        Assert-NoLiteral $captured.Text 'verbose output'
        Assert-NoLiteral ([System.IO.File]::ReadAllText($script:audit)) 'the audit file'
        Assert-NoLiteral ([System.IO.File]::ReadAllText($script:out)) 'the -OutFile plan'
        Assert-NoLiteral (Invoke-InTenure { param($p) Get-TenureCanonicalJson -InputObject $p } @($plan)) 'the canonical plan'
    }

    It 'is converted to SecureString when a provider stores it as a plain string' {
        $state = $script:state
        $literal = $script:Literal
        $plain = {
            param($Target, $Desired, $Current, $Context)
            $Context.Secrets[$Context.StepId] = $literal
            foreach ($key in $Desired.Keys) { $state[$Target.Id][$key] = $Desired[$key] }
            [pscustomobject]$state[$Target.Id].Clone()
        }.GetNewClosure()
        Register-TestProvider (New-FakeProviderDefinition -Name 'Fake.Plain' -State $script:state -Overrides @{ Set = $plain })
        $plan = New-TestPlan -Steps @(New-SecretStep 'S01' 'Fake.Plain')
        $captured = Invoke-Captured $plan

        $plan.Steps[0].Status | Should -Be 'Applied'
        $captured.Result.Secrets['S01'] | Should -BeOfType [securestring]
        ConvertFrom-TestSecureString $captured.Result.Secrets['S01'] | Should -Be $script:Literal
        $captured.Text | Should -Match 'converted to SecureString'
        Assert-NoLiteral $captured.Text 'the warning about it'
        Assert-NoLiteral ([System.IO.File]::ReadAllText($script:audit)) 'the audit file'
    }
}

Describe 'The capture itself' {
    BeforeEach { New-SecretWorld }

    It 'collects the debug stream as well as verbose, so a secret written with Write-Debug would be found' {
        $state = $script:state
        $get = { param($Target, $Context) Write-Debug 'debug-probe-line-5' -Debug; [pscustomobject]$state[$Target.Id].Clone() }.GetNewClosure()
        Register-TestProvider (New-FakeProviderDefinition -Name 'Fake.State' -State $script:state -Overrides @{ Get = $get })
        $plan = New-TestPlan -Steps @(New-SecretStep 'S01' 'Fake.State')
        $captured = Invoke-Captured $plan
        $captured.Text | Should -Match 'debug-probe-line-5'
        $captured.Text | Should -Match '\[S01\]' -Because 'verbose lines are captured too'
    }
}

Describe 'A SecureString inside provider state' {
    BeforeEach {
        New-SecretWorld
        $literal = $script:Literal
        $get = {
            param($Target, $Context)
            $secure = [securestring]::new()
            foreach ($character in $literal.ToCharArray()) { $secure.AppendChar($character) }
            [pscustomobject]@{ accountEnabled = $true; department = 'Sales'; recoveryKey = $secure }
        }.GetNewClosure()
        Register-TestProvider (New-FakeProviderDefinition -Name 'Fake.SecretGet' -State $script:state -Overrides @{ Get = $get })
    }

    It 'fails the step with Tenure.Json.SecretRejected and keeps it out of the audit log' {
        $plan = New-TestPlan -Steps @(New-TestStep -Id 'S01' -Provider 'Fake.SecretGet' -Target @{ Kind = 'user'; Id = 'u1'; Name = 'u1@example.com' } -Before ([pscustomobject]@{ accountEnabled = $true; department = 'Sales' }) -After @{ accountEnabled = $false })
        $captured = Invoke-Captured $plan

        $plan.Steps[0].Status | Should -Be 'Failed'
        $plan.Steps[0].Result.Error | Should -Match '^Tenure\.Json\.SecretRejected'
        $plan.Steps[0].Result.Observed | Should -BeNullOrEmpty
        $script:state['u1']['accountEnabled'] | Should -BeTrue -Because 'Set must not run on state that cannot be recorded'
        $audit = [System.IO.File]::ReadAllText($script:audit)
        Assert-NoLiteral $audit 'the audit file'
        $audit | Should -Not -Match 'recoveryKey'
        Assert-NoLiteral $captured.Text 'verbose output'
        (Test-TenureAudit -Path $script:audit).Valid | Should -BeTrue
        { Invoke-InTenure { param($p) Get-TenureCanonicalJson -InputObject $p } @($plan) } | Should -Not -Throw
    }

    It 'also fails a Create step that has no fingerprint to compare' {
        $plan = New-TestPlan -Steps @(New-TestStep -Id 'S01' -Provider 'Fake.SecretGet' -Action 'Create' -Target @{ Kind = 'user'; Id = 'u9'; Name = 'u9@example.com' } -After @{ accountEnabled = $true })
        Invoke-Captured $plan | Out-Null
        $plan.Steps[0].Status | Should -Be 'Failed'
        $plan.Steps[0].Result.Error | Should -Match 'SecretRejected'
        Assert-NoLiteral ([System.IO.File]::ReadAllText($script:audit)) 'the audit file'
    }
}

Describe 'A plain-string secret written by a provider Get' {
    BeforeEach { New-SecretWorld }

    It 'is converted to SecureString and searched for, so state that echoes it is withheld' {
        $state = $script:state
        $literal = $script:Literal
        $get = {
            param($Target, $Context)
            $Context.Secrets[$Context.StepId] = $literal
            $current = [pscustomobject]$state[$Target.Id].Clone()
            $current | Add-Member -NotePropertyName 'hint' -NotePropertyValue "temporary code $literal"
            $current
        }.GetNewClosure()
        Register-TestProvider (New-FakeProviderDefinition -Name 'Fake.PlainGet' -State $script:state -Overrides @{ Get = $get })
        $plan = New-TestPlan -Steps @(New-TestStep -Id 'S01' -Provider 'Fake.PlainGet' -Action 'Create' -Target @{ Kind = 'user'; Id = 'u1'; Name = 'u1@example.com' } -After @{ accountEnabled = $false })
        $captured = Invoke-Captured $plan

        $plan.Steps[0].Status | Should -Be 'Failed'
        $plan.Steps[0].Result.Error | Should -Match 'SecretRejected'
        $captured.Result.Secrets['S01'] | Should -BeOfType [securestring]
        $script:state['u1']['accountEnabled'] | Should -BeTrue -Because 'Set must not run'
        Assert-NoLiteral $captured.Text 'verbose and warning output'
        Assert-NoLiteral ([System.IO.File]::ReadAllText($script:audit)) 'the audit file'
        Assert-NoLiteral ([System.IO.File]::ReadAllText($script:out)) 'the -OutFile plan'
    }
}
